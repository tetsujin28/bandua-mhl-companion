pub fn status_label(lang: &str, s: Status) -> &'static str {
    t(
        lang,
        match s {
            Status::Ok => "s_ok",
            Status::NoHash => "s_no_hash",
            Status::Corrupt => "s_corrupt",
            Status::Missing => "s_missing",
            Status::Size => "s_size",
            Status::Unreadable => "s_unreadable",
        },
    )
}

/// Taille lisible (o/Ko/Mo en français, B/KB/MB sinon), en puissances de 1000.
pub fn human_bytes(lang: &str, b: u64) -> String {
    let units = if lang == "fr" { ["o", "Ko", "Mo", "Go", "To"] } else { ["B", "KB", "MB", "GB", "TB"] };
    let mut v = b as f64;
    let mut u = 0;
    while v >= 1000.0 && u < units.len() - 1 {
        v /= 1000.0;
        u += 1;
    }
    let txt = if u == 0 { format!("{b} {}", units[0]) } else { format!("{v:.2} {}", units[u]) };
    if lang == "en" {
        txt
    } else {
        txt.replace('.', ",")
    }
}

fn dur(s: f64) -> String {
    let s = s.round() as u64;
    if s >= 3600 {
        format!("{}h{:02}m{:02}s", s / 3600, s % 3600 / 60, s % 60)
    } else if s >= 60 {
        format!("{}m{:02}s", s / 60, s % 60)
    } else {
        format!("{s}s")
    }
}

pub fn text(r: &Report, lang: &str) -> String {
    let l = lang;
    let mut x = String::new();
    let rule = "=".repeat(72);
    let thin = "-".repeat(72);
    let _ = writeln!(x, "{rule}\n{}  ·  {APP_NAME}\n{rule}", t(l, "title"));
    let _ = writeln!(x, "{:<18}{}", t(l, "source"), r.source.display());
    let _ = writeln!(x, "{:<18}{}", t(l, "date"), r.finished.format("%Y-%m-%d %H:%M:%S"));
    let _ = writeln!(x, "{:<18}{}", t(l, "duration"), dur(r.duration_s));
    let verdict = if r.cancelled {
        t(l, "v_cancel")
    } else if r.ok {
        t(l, "v_ok")
    } else {
        t(l, "v_bad")
    };
    let _ = writeln!(x, "{:<18}{}", t(l, "verdict"), verdict);
    let _ = writeln!(
        x,
        "{:<18}{} ({}) · {} {} · {} {}",
        t(l, "files"),
        r.total_files,
        human_bytes(l, r.total_bytes),
        r.ok_files,
        t(l, "ok_files"),
        r.problems,
        t(l, "problems")
    );
    if r.no_hash > 0 {
        let _ = writeln!(x, "{:<18}{} {}", "", r.no_hash, t(l, "no_hash"));
    }
    if r.extra_total > 0 {
        let _ = writeln!(x, "{:<18}{} {}", "", r.extra_total, t(l, "extra"));
    }

    for p in &r.packages {
        let _ = writeln!(x, "\n{rule}");
        let name = if p.location.is_empty() || p.location == p.label { p.label.clone() } else { format!("{}  ({})", p.label, p.location) };
        let _ = writeln!(x, "{name}");
        let _ = writeln!(x, "{thin}");
        let kind = match p.kind {
            Kind::Mhl1 => "MHL 1.1",
            Kind::Asc => "ASC MHL",
        };
        let _ = writeln!(x, "{:<18}{} · {}", t(l, "manifest"), kind, p.manifest.display());
        if let Some(tool) = &p.tool {
            let _ = writeln!(x, "{:<18}{tool}", t(l, "tool"));
        }
        let _ = writeln!(x, "{:<18}{}", t(l, "algo"), p.algos.join(", "));
        let _ = writeln!(
            x,
            "{:<18}{} ({}) · {} {} · {} {}",
            t(l, "files"),
            p.total_files,
            human_bytes(l, p.total_bytes),
            p.ok_files,
            t(l, "ok_files"),
            p.problems(),
            t(l, "problems")
        );
        if p.chain_broken {
            let _ = writeln!(x, "!! {}", t(l, "chain"));
        }
        let bad: Vec<_> = p.issues.iter().filter(|i| i.status.is_problem()).collect();
        if !bad.is_empty() {
            let _ = writeln!(x, "\n{}", t(l, "issues"));
            for i in bad {
                let _ = writeln!(x, "  [{}] {}", status_label(l, i.status), i.rel);
                let why = match i.status {
                    Status::Corrupt => t(l, "d_corrupt").to_string(),
                    Status::Missing => t(l, "d_missing").to_string(),
                    Status::Size => format!(
                        "{} : {} {}, {} {}",
                        t(l, "d_size"),
                        t(l, "expected"),
                        i.expected_size.map(|s| s.to_string()).unwrap_or("?".into()),
                        t(l, "found"),
                        i.actual_size.map(|s| s.to_string()).unwrap_or("?".into())
                    ),
                    Status::Unreadable => format!("{} : {}", t(l, "d_unreadable"), i.detail.clone().unwrap_or_default()),
                    _ => String::new(),
                };
                let _ = writeln!(x, "      {why}");
                if i.status == Status::Corrupt {
                    let _ = writeln!(
                        x,
                        "      {} {} {}\n      {} {} {}",
                        i.algo.clone().unwrap_or_default(),
                        t(l, "expected"),
                        i.expected_hash.clone().unwrap_or_default(),
                        i.algo.clone().unwrap_or_default(),
                        t(l, "found"),
                        i.actual_hash.clone().unwrap_or_default()
                    );
                }
            }
        }
        let nh: Vec<_> = p.issues.iter().filter(|i| i.status == Status::NoHash).collect();
        if !nh.is_empty() {
            let _ = writeln!(x, "\n{} ({})", t(l, "s_no_hash"), t(l, "no_hash"));
            for i in nh.iter().take(100) {
                let _ = writeln!(x, "  {}", i.rel);
            }
        }
        if !p.clips.is_empty() {
            let _ = writeln!(x, "\n{}", t(l, "clips"));
            for c in &p.clips {
                let _ = writeln!(
                    x,
                    "  {:<12}{:<44}{:>12}  {}",
                    status_label(l, c.status),
                    c.name,
                    human_bytes(l, c.bytes),
                    if c.brand_label == "Générique" { ["Générique", "Generic", "Genérico"][usize::from(l == "en") + 2 * usize::from(l == "es")] } else { c.brand_label.as_str() }
                );
            }
        }
        if p.extra_total > 0 {
            let _ = writeln!(x, "\n{} ({})", t(l, "extra_list"), p.extra_total);
            for e in p.extra.iter().take(200) {
                let _ = writeln!(x, "  {e}");
            }
            if p.extra_total > 200 {
                let _ = writeln!(x, "  {}", t(l, "more").replace("{n}", &(p.extra_total - 200).to_string()));
            }
        }
    }
    let _ = writeln!(
        x,
        "\n{rule}\n{}",
        t(l, "footer").replace("{app}", APP_NAME).replace("{v}", APP_VERSION).replace("{a}", APP_AUTHOR)
    );
    x
}
